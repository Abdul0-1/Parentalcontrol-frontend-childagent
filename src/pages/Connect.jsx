import { useState } from "react";
import { useNavigate } from "react-router-dom";
import api from "../api";

function getOrCreateUuid() {
  let id = localStorage.getItem("deviceUuid");

  if (!id) {
    id = crypto.randomUUID();
    localStorage.setItem("deviceUuid", id);
  }

  return id;
}

export default function Connect() {
  const [code, setCode] = useState("");
  const [deviceName, setDeviceName] = useState("");
  const [error, setError] = useState("");
  const [message, setMessage] = useState("");
  const navigate = useNavigate();

  async function pair(e) {
    e.preventDefault();
    setError("");
    setMessage("");

    try {
      const res = await api.post("/device/pair", {
        pairingCode: code.trim().toUpperCase(),
        deviceName: deviceName || "Child Browser Device",
        deviceUuid: getOrCreateUuid(),
        platform: navigator.userAgent
      });

      localStorage.setItem("deviceToken", res.data.token);
      localStorage.setItem("deviceId", res.data.deviceId);
      localStorage.setItem("childName", res.data.childName);

      setMessage(`Paired with ${res.data.childName}`);
      navigate("/agent");
    } catch (err) {
      setError(err.response?.data || "Pairing failed");
    }
  }

  return (
    <div className="child-page">
      <form className="child-card" onSubmit={pair}>
        <h1>FamilyShield</h1>
        <h2>Connect This Device</h2>

        <p>
          Enter the one-time pairing code generated by the parent.
          This device will only share information after pairing and permission.
        </p>

        <label>Pairing code</label>
        <input
          placeholder="ABCD-1234"
          value={code}
          onChange={e => setCode(e.target.value)}
          required
        />

        <label>Device name</label>
        <input
          placeholder="My phone / My laptop"
          value={deviceName}
          onChange={e => setDeviceName(e.target.value)}
        />

        {error && <div className="error">{error}</div>}
        {message && <div className="success">{message}</div>}

        <button>Pair Device</button>
      </form>
    </div>
  );
}
